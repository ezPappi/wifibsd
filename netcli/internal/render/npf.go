// Package render turns a configuration into the native NetBSD files and
// commands: npf.conf(5), hostapd.conf, wpa_supplicant.conf and dhcpd.conf.
package render

import (
	"fmt"
	"net/netip"
	"sort"
	"strconv"
	"strings"

	"github.com/netcli/netcli/internal/config"
)

const header = "# Generated by netcli. Do not edit: changes are overwritten.\n# Edit the configuration with netcli instead.\n"

// NPFUsesLog reports whether any access-list entry logs, which requires the
// npflog0 interface.
func NPFUsesLog(c *config.Config) bool {
	for name, ifc := range c.Interfaces {
		_ = name
		for _, g := range []string{ifc.AccessGroupIn, ifc.AccessGroupOut} {
			if acl, ok := c.AccessLists[g]; ok {
				for _, e := range acl.Entries {
					if e.Log {
						return true
					}
				}
			}
		}
	}
	return false
}

// NPF renders npf.conf for the configuration.
func NPF(c *config.Config) string {
	var b strings.Builder
	b.WriteString(header)
	b.WriteString("\n")

	if NPFUsesLog(c) {
		b.WriteString("procedure \"log\" {\n\tlog: npflog0\n}\n\n")
	}

	// NAT. ifaddrs() tracks interface addresses dynamically, so a WAN
	// address obtained later by DHCP is picked up without a reload.
	if len(c.NAT) > 0 {
		for _, n := range c.NAT {
			switch n.Type {
			case config.NATOverload:
				fmt.Fprintf(&b, "map %s dynamic %s -> ifaddrs(%s)\n", n.Interface, n.Source, n.Interface)
			case config.NATStatic:
				fmt.Fprintf(&b, "map %s dynamic proto %s %s port %d <- ifaddrs(%s) port %d\n",
					n.Interface, n.Protocol, n.LocalAddr, n.LocalPort, n.Interface, n.PublicPort)
			}
		}
		b.WriteString("\n")
	}

	for _, ifn := range c.InterfaceNames() {
		ifc := c.Interfaces[ifn]
		in, inOK := c.AccessLists[ifc.AccessGroupIn]
		out, outOK := c.AccessLists[ifc.AccessGroupOut]
		if !inOK && !outOK {
			continue
		}
		fmt.Fprintf(&b, "group \"%s\" on %s {\n", ifn, ifn)
		if inOK {
			fmt.Fprintf(&b, "\t# access-list %s in\n", ifc.AccessGroupIn)
			for _, r := range infraRules(ifc) {
				b.WriteString("\t" + r + "\n")
			}
			for _, e := range in.Entries {
				b.WriteString("\t" + Rule(e, "in") + "\n")
			}
			b.WriteString("\tblock in final all\t# implicit deny\n")
		} else {
			b.WriteString("\tpass stateful in final all\n")
		}
		if outOK {
			fmt.Fprintf(&b, "\t# access-list %s out\n", ifc.AccessGroupOut)
			for _, e := range out.Entries {
				b.WriteString("\t" + Rule(e, "out") + "\n")
			}
			b.WriteString("\tblock out final all\t# implicit deny\n")
		} else {
			b.WriteString("\tpass stateful out final all\n")
		}
		b.WriteString("}\n\n")
	}

	b.WriteString("group default {\n\tpass final on lo0 all\n\tpass final all\n}\n")
	return b.String()
}

// infraRules keeps protocols working that stateful tracking cannot cover:
// IPv6 neighbour discovery and DHCP replies on dhcp-client interfaces.
func infraRules(ifc *config.Interface) []string {
	var r []string
	if len(ifc.IPv6) > 0 {
		r = append(r, "pass in final family inet6 proto ipv6-icmp icmp-type 133 all\t# router solicitation")
		r = append(r, "pass in final family inet6 proto ipv6-icmp icmp-type 134 all\t# router advertisement")
		r = append(r, "pass in final family inet6 proto ipv6-icmp icmp-type 135 all\t# neighbour solicitation")
		r = append(r, "pass in final family inet6 proto ipv6-icmp icmp-type 136 all\t# neighbour advertisement")
	}
	if ifc.DHCP {
		r = append(r, "pass in final proto udp from any port 67 to any port 68\t# dhcp client")
	}
	return r
}

// Rule renders one access-list entry as an NPF rule.
func Rule(e config.ACE, dir string) string {
	var b strings.Builder
	if e.Action == "permit" {
		b.WriteString("pass")
		if !e.Stateless {
			b.WriteString(" stateful")
		}
	} else {
		b.WriteString("block")
	}
	b.WriteString(" " + dir + " final")

	switch e.Protocol {
	case "ip":
	case "icmpv6":
		b.WriteString(" proto ipv6-icmp")
	default:
		b.WriteString(" proto " + e.Protocol)
	}
	if e.ICMPType != nil {
		b.WriteString(" icmp-type " + strconv.Itoa(*e.ICMPType))
	}
	if e.Source == "any" && e.Destination == "any" && e.SourcePort == "" && e.DestinationPort == "" {
		b.WriteString(" all")
	} else {
		b.WriteString(" from " + npfAddr(e.Source))
		if e.SourcePort != "" {
			b.WriteString(" port " + e.SourcePort)
		}
		b.WriteString(" to " + npfAddr(e.Destination))
		if e.DestinationPort != "" {
			b.WriteString(" port " + e.DestinationPort)
		}
	}
	if e.Log {
		b.WriteString(" apply \"log\"")
	}
	return b.String()
}

func npfAddr(a string) string {
	if a == "any" {
		return "any"
	}
	if p, err := netip.ParsePrefix(a); err == nil && p.IsSingleIP() {
		return p.Addr().String()
	}
	return a
}

func sortedKeys(m map[string]bool) []string {
	k := make([]string, 0, len(m))
	for s := range m {
		k = append(k, s)
	}
	sort.Strings(k)
	return k
}
